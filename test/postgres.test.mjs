const url=process.env.DATABASE_URL;
async function database(t) {
  const pool=new pg.Pool({connectionString:url});
  const schema=`test_colour_${randomBytes(6).toString('hex')}`;
  await pool.query(`CREATE SCHEMA ${schema}`);
  t.after(async()=>{assert.match(schema,/^test_colour_[a-f0-9]+$/);await pool.query(`DROP SCHEMA ${schema} CASCADE`);await pool.end()});
  return schema;
}
test('PostgreSQL serialises wallet debits, retries, opposing bets and competing settlement workers',{skip:!url},async t=>{
  const schema=await database(t);let now=1800000000000;
  const store=await createPgStore(url,{schema,clock:()=>now});t.after(()=>store.close());
  const id=await store.register('concurrent@example.test','Concurrent','hash','salt',now);
  const other=await store.register('other@example.test','Other','hash','salt',now);
  await store.tick(now);const round=(await store.state(30,id,now)).round;
  const bet={round:round.id,selection:'GREEN',base:1000,multiplier:10,key:'concurrent-request-0001'};
  const results=await Promise.all([store.place(id,bet),store.place(id,bet)]);
  assert.equal(results[0].id,results[1].id);assert.equal((await store.get('SELECT balance FROM users WHERE id=?',id)).balance,0);
  await assert.rejects(store.place(id,{...bet,key:'concurrent-request-0002'}),/Not enough/);
  const conflict=await Promise.allSettled([store.place(other,{...bet,base:10,key:'opposition-green-001'}),store.place(other,{...bet,base:10,selection:'RED',key:'opposition-red-0001'})]);
  assert.equal(conflict.filter(r=>r.status==='fulfilled').length,1);
  now=round.end;await Promise.all([store.tick(now),store.tick(now)]);
  assert.equal((await store.get('SELECT COUNT(*)::integer AS count FROM bets WHERE payout IS NULL')).count,0);
  const before=await store.all('SELECT * FROM ledger ORDER BY id');await store.tick(now);assert.deepEqual(await store.all('SELECT * FROM ledger ORDER BY id'),before);
  for(const u of await store.all('SELECT id,balance FROM users'))assert.equal(u.balance,(await store.get('SELECT SUM(amount)::bigint AS balance FROM ledger WHERE user_id=?',u.id)).balance);
  const state=await store.state(30,id,now);assert.equal(state.history[0].audit,undefined);
});
test('PostgreSQL checks cutoff after waiting for a wallet lock',{skip:!url},async t=>{
  const schema=await database(t);let now=1800000000000;
  const store=await createPgStore(url,{schema,clock:()=>now});t.after(()=>store.close());
  const id=await store.register('lock@example.test','Lock','hash','salt',now);await store.tick(now);
  const r=(await store.state(30,id,now)).round;const client=await store.pool.connect();
  await client.query('BEGIN');await client.query('SELECT id FROM users WHERE id=$1 FOR UPDATE',[id]);
  const pending=store.place(id,{round:r.id,selection:'RED',base:10,multiplier:1,key:'locked-wallet-request'});
  now=r.lock;await client.query('COMMIT');client.release();
  await assert.rejects(pending,/locked/);assert.equal((await store.get('SELECT balance FROM users WHERE id=?',id)).balance,1000000);
});
