test('HTTP registration, cookies, privacy, request protection and session rotation', async t => {
  let now = 1800000000000;
  const app = await createApp({ clock: () => now });
  app.server.listen(0, '127.0.0.1');
  await once(app.server, 'listening');
  t.after(() => new Promise(resolve => app.server.close(resolve)));
  const origin = `http://127.0.0.1:${app.server.address().port}`;
  let cookie;
  const post = (path, input, headers = {}) => fetch(origin + path, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: origin, ...(cookie ? { Cookie: cookie } : {}), ...headers }, body: JSON.stringify(input) });
  const account = { email: 'integration@example.com', password: 'a long unique test password', name: 'Integration', accepted: true };
  assert.equal((await post('/api/register', account, { Origin: 'https://attacker.invalid' })).status, 403);
  assert.equal((await post('/api/register', { ...account, accepted: false })).status, 400);
  let response = await post('/api/register', account);
  assert.equal(response.status, 200);
  const setCookie = response.headers.get('set-cookie');
  assert.match(setCookie, /HttpOnly/); assert.match(setCookie, /SameSite=Lax/);
  cookie = setCookie.split(';')[0];
  const state = await (await fetch(origin + '/api/state?room=30', { headers: { Cookie: cookie } })).json();
  assert.equal(state.user.balance, 1000000);
  assert.equal(state.verificationRequired, false);
  assert.equal(state.registrationEnabled, true);
  assert.equal(state.emailAvailable, false);
  assert.equal(state.user.password, undefined);
  const bet = { round: state.round.id, selection: 'GREEN', base: 1000, multiplier: 10, key: 'integration-key-0001' };
  const replies = await Promise.all([post('/api/bets', bet), post('/api/bets', bet)]);
  assert.deepEqual(replies.map(r => r.status), [200, 200]);
  assert.equal(app.store.get('SELECT COUNT(*) AS count FROM bets').count, 1);
  assert.equal((await post('/api/bets', { ...bet, key: 'integration-key-0002' })).status, 400);
  const anonymous = await (await fetch(origin + '/api/state')).json();
  assert.equal(anonymous.user, null); assert.deepEqual(anonymous.bets, []); assert.deepEqual(anonymous.ledger, []);
  now = state.round.end; await app.tick();
  assert.notEqual(app.store.get('SELECT result FROM rounds WHERE id=?', state.round.id).result, null);
  assert.equal((await post('/api/logout', {})).status, 200);
  assert.equal((await post('/api/bets', bet)).status, 401);
  response = await post('/api/login', { email: account.email, password: account.password });
  assert.equal(response.status, 200);
  assert.notEqual(response.headers.get('set-cookie').split(';')[0], cookie);
  assert.equal((await fetch(origin + '/../../server.mjs')).status, 404);
  assert.equal((await post('/api/login', { email: account.email, password: 'incorrect but long password' })).status, 401);
});
